#!/usr/bin/env node
/**
 * One-off asset pipeline: decode the original design-canvas bundle and emit the
 * WebP assets this app serves.
 *
 *   node scripts/prepare-assets.mjs ../l2-arena/index.html
 *
 * The source bundle (knbl-ai/l2-arena, a single 23 MB index.html) is NOT part of
 * this repo. Re-run this only when the upstream artifact changes.
 *
 * Writes: public/img/*.webp, app/icon.png, lib/assets.ts, and template.html +
 * assets/ under .bundle-src/ for reference while porting.
 */
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import sharp from 'sharp';
import { NAMED, SKIP, buildPartnerMap } from './asset-map.mjs';

const src = process.argv[2];
if (!src) { console.error('usage: prepare-assets.mjs <path-to-l2-arena/index.html>'); process.exit(1); }

const html = fs.readFileSync(src, 'utf8');
const grab = (type) => {
  const m = html.match(new RegExp(`<script type="__bundler/${type}">([\\s\\S]*?)</script>`));
  if (!m) throw new Error(`bundle section "${type}" not found`);
  return m[1];
};

const manifest = JSON.parse(grab('manifest'));
const template = JSON.parse(grab('template'));

const outDir = path.resolve('public/img');
const refDir = path.resolve('.bundle-src');
fs.mkdirSync(outDir, { recursive: true });
fs.mkdirSync(refDir, { recursive: true });
fs.writeFileSync(path.join(refDir, 'template.html'), template);

const names = { ...NAMED, ...buildPartnerMap(template) };

const decode = (entry) => {
  let buf = Buffer.from(entry.data, 'base64');
  if (entry.compressed) {
    for (const fn of [zlib.gunzipSync, zlib.inflateSync, zlib.brotliDecompressSync]) {
      try { return fn(buf); } catch { /* try next */ }
    }
    throw new Error('could not decompress entry');
  }
  return buf;
};

const assets = {};
let unnamed = 0;

for (const [uuid, entry] of Object.entries(manifest)) {
  if (SKIP.has(uuid)) continue;
  if (!entry.mime.startsWith('image/')) continue;

  const name = names[uuid];
  if (!name) { console.warn(`  ! unnamed image asset ${uuid} (${entry.mime})`); unnamed++; continue; }

  const buf = decode(entry);

  if (name === 'icon') {                       // favicon stays PNG for app/icon.png
    fs.writeFileSync(path.resolve('app/icon.png'), buf);
    continue;
  }

  const file = path.join(outDir, `${name}.webp`);
  if (fs.existsSync(file)) continue;           // byte-identical duplicates share one file

  const out = await sharp(buf).webp({ quality: 82 }).toBuffer();
  const { width, height } = await sharp(out).metadata();
  fs.writeFileSync(file, out);
  assets[name] = { src: `/img/${name}.webp`, width, height };
}

const entries = Object.entries(assets).sort(([a], [b]) => a.localeCompare(b));
fs.writeFileSync(path.resolve('lib/assets.ts'),
`// GENERATED by scripts/prepare-assets.mjs — do not edit.
export type Asset = { src: string; width: number; height: number };

export const assets = {
${entries.map(([k, v]) => `  '${k}': { src: '${v.src}', width: ${v.width}, height: ${v.height} },`).join('\n')}
} as const satisfies Record<string, Asset>;

export type AssetName = keyof typeof assets;
export const img = (name: AssetName): Asset => assets[name];

/** The 60 partner logos, in the order they appear in the grid. */
export const partnerLogos = Object.keys(assets)
  .filter((k) => k.startsWith('partner-'))
  .sort() as AssetName[];
`);

const total = entries.reduce((n, [, v]) => n + fs.statSync(path.join(outDir, path.basename(v.src))).size, 0);
console.log(`wrote ${entries.length} webp assets (${(total / 1e6).toFixed(2)} MB) + app/icon.png`);
if (unnamed) console.warn(`${unnamed} image asset(s) had no name mapping`);
